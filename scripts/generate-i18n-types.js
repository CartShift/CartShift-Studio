/**
 * Generate TypeScript types from translation files
 * Run via: `npm run i18n:types` or automatically during build
 *
 * Benefits:
 * - Catch translation key typos at compile time
 * - Full autocomplete in IDE
 * - Refactoring support (rename keys automatically)
 * - Self-documenting code structure
 */
const fs = require('fs');
const path = require('path');

const messagesDir = path.join(__dirname, '..', 'messages');
const srcDir = path.join(messagesDir, 'src');
const locales = ['en', 'he'];

/**
 * Recursively extract all translation keys from an object
 */
function extractKeys(obj, prefix = '') {
  const keys = [];

  for (const [key, value] of Object.entries(obj)) {
    const fullKey = prefix ? `${prefix}.${key}` : key;

    if (typeof value === 'string' || Array.isArray(value)) {
      keys.push(fullKey);
    } else if (typeof value === 'object' && value !== null) {
      keys.push(...extractKeys(value, fullKey));
    }
  }

  return keys;
}

/**
 * Generate TypeScript union type with all keys
 */
function generateUnionType(keys) {
  return `export type TranslationKey =\n  ${keys.map(k => `  | '${k}'`).join('\n')};\n`;
}

/**
 * Generate interface-based types (better for autocomplete)
 */
function generateNamespaceTypes(mergedTranslations) {
  let output = `// Auto-generated from translation files\n// DO NOT EDIT THIS FILE DIRECTLY\n\n`;

  for (const [namespace, translations] of Object.entries(mergedTranslations)) {
    output += `export interface ${namespace.charAt(0).toUpperCase() + namespace.slice(1)} {\n`;

    const lines = [];
    function processObject(obj, indent = '') {
      for (const [key, value] of Object.entries(obj)) {
        if (typeof value === 'string' || Array.isArray(value)) {
          lines.push(`${indent}${key}: string;`);
        } else if (typeof value === 'object' && value !== null) {
          const newIndent = indent + '  ';
          lines.push(`${indent}${key}: {`);
          processObject(value, newIndent);
          lines.push(`${indent}};`);
        }
      }
    }

    processObject(translations);
    output += lines.join('\n');
    output += '\n}\n\n';
  }

  return output;
}

/**
 * Main generation function
 */
async function generateTypes() {
  console.log('🔧 Generating TypeScript types from translations...\n');

  // Load merged translations (generated files)
  const enTranslations = JSON.parse(fs.readFileSync(path.join(messagesDir, 'en.json'), 'utf8'));
  const heTranslations = JSON.parse(fs.readFileSync(path.join(messagesDir, 'he.json'), 'utf8'));

  // Extract all keys
  const allKeys = new Set([
    ...extractKeys(enTranslations),
    ...extractKeys(heTranslations)
  ]);

  const sortedKeys = Array.from(allKeys).sort();

  // Generate output file
  const outputPath = path.join(__dirname, '..', 'lib', 'types', 'i18n.ts');
  const outputDir = path.dirname(outputPath);

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Generate interface-based types (better for autocomplete)
  // Extract top-level keys as interfaces
  const namespaces = {};
  for (const [key, value] of Object.entries(enTranslations)) {
    if (key === '_meta') continue;
    namespaces[key] = value;
  }

  let output = `/**\n * Translation Type Definitions\n * Auto-generated from translation files\n * Last updated: ${new Date().toISOString()}\n * \n * Usage:\n * import { Portal, Common } from '~/lib/types/i18n';\n * const t = useTranslations<Portal>('portal');\n * const value = t.requests.form.titleLabel; // Fully typed!\n */\n\n`;

  // Add namespace types
  output += generateNamespaceTypes(namespaces);

  // Add union type for backward compatibility
  output += generateUnionType(sortedKeys);

  // Add helper type for namespaces
  const namespaceNames = Object.keys(namespaces).filter(n => n !== '_meta');
  output += `\n\nexport type TranslationNamespace =\n  ${namespaceNames.map(n => `  | '${n}'`).join('\n')};\n`;

  // Write output
  fs.writeFileSync(outputPath, output, 'utf8');

  console.log(`✅ Types generated to: ${path.relative(process.cwd(), outputPath)}`);
  console.log(`   Keys: ${sortedKeys.length}`);
  console.log(`   Interfaces: ${namespaceNames.length}`);
}

generateTypes().catch(error => {
  console.error('❌ Failed to generate types:', error.message);
  process.exit(1);
});
